clear;
clc;
close all;

% --- Ορισμός παραμέτρων δειγματοληψίας ---
% Το σήμα υπάρχει στο διάστημα [-3, 3]. Θα επιλέξουμε ένα μεγαλύτερο διάστημα
% για να αποφύγουμε σφάλματα 'aliasing' και να προσομοιώσουμε καλύτερα
% τον συνεχόμενο χρόνο.
T_start = -5; % Αρχή χρόνου
T_end = 5;    % Τέλος χρόνου
Fs = 1000;    % Συχνότητα δειγματοληψίας (Hz), αρκετά υψηλή
Ts = 1/Fs;    % Περίοδος δειγματοληψίας
t = T_start:Ts:T_end; % Διάνυσμα χρόνου
N = length(t); % Αριθμός δειγμάτων

% --- Ορισμός του σήματος x(t) ---
x = zeros(1, N); % Αρχικοποίηση του σήματος ως μηδέν

% Διάστημα 1: -3 <= t <= -2, x(t) = 2
idx1 = (t >= -3) & (t <= -2);
x(idx1) = 2;

% Διάστημα 2: |t| < 2, δηλαδή -2 < t < 2, x(t) = |t| + 2
% 2a: -2 < t < 0, x(t) = -t + 2
idx2a = (t > -2) & (t < 0);
x(idx2a) = -t(idx2a) + 2;

% 2b: 0 <= t < 2, x(t) = t + 2
idx2b = (t >= 0) & (t < 2);
x(idx2b) = t(idx2b) + 2;

% Διάστημα 3: 2 <= t < 3, x(t) = 1.5
idx3 = (t >= 2) & (t < 3);
x(idx3) = 1.5;

% --- Υπολογισμός του Fourier Transform (FFT) ---
% Χρησιμοποιούμε την fft για τον υπολογισμό του DFT
X_fft = fft(x);

% --- Στρέβλωση (Shift) του φάσματος ---
% Η fft υπολογίζει το φάσμα από 0 έως Fs. Χρησιμοποιούμε fftshift για να
% μεταφέρουμε το μηδενικό σημείο συχνότητας (DC) στο κέντρο.
X_shift = fftshift(X_fft);

% --- Δημιουργία του άξονα συχνότητας ---
% Ο άξονας συχνότητας για το μετατοπισμένο φάσμα.
f = (-N/2 : N/2 - 1) * (Fs/N); 
% Για μη-περιοδικά σήματα, ο άξονας omega (rad/s) είναι:
% omega = 2*pi*f;

% --- Υπολογισμός Φασματικού Διαγράμματος Πλάτους ---
% Πλάτος (Magnitude)
Magnitude_Spectrum = abs(X_shift);

% Ο μετασχηματισμός Fourier ενός σήματος συνεχούς χρόνου X(\omega)
% προσεγγίζεται από τον DFT (X_fft) ως: X(\omega) \approx Ts * X_{fft}
% Επειδή ενδιαφερόμαστε για το σχήμα (πλάτος), μπορούμε να παραλείψουμε το Ts
% για την απλή σχεδίαση, αλλά για σωστή μονάδα:
Magnitude_Spectrum_scaled = Ts * Magnitude_Spectrum; 

% --- Υπολογισμός Φασματικού Διαγράμματος Φάσης ---
% Φάση (Phase) σε ακτίνια
Phase_Spectrum = angle(X_shift);

% --- Σχεδίαση των Διαγραμμάτων ---
figure;

% 1. Σχεδίαση του Σήματος στο Χρόνο (x(t)) (Προαιρετικό, αλλά χρήσιμο)
subplot(3, 1, 1);
plot(t, x);
title('Σήμα Χρόνου x(t)');
xlabel('Χρόνος t (sec)');
ylabel('x(t)');
grid on;
xlim([T_start, T_end]);

% 2. Σχεδίαση του Φασματικού Διαγράμματος Πλάτους
subplot(3, 1, 2);
plot(f, Magnitude_Spectrum_scaled);
title('Φασματικό Διάγραμμα Πλάτους |X(f)|');
xlabel('Συχνότητα f (Hz)');
ylabel('|X(f)|');
grid on;
xlim([-10, 10]); % Εστίαση σε χαμηλές συχνότητες, όπου είναι το ενδιαφέρον

% 3. Σχεδίαση του Φασματικού Διαγράμματος Φάσης
subplot(3, 1, 3);
plot(f, Phase_Spectrum);
title('Φασματικό Διάγραμμα Φάσης \angle X(f)');
xlabel('Συχνότητα f (Hz)');
ylabel('Φάση (rad)');
grid on;
xlim([-10, 10]); % Εστίαση σε χαμηλές συχνότητες

% Βελτίωση εμφάνισης παραθύρου (προαιρετικό)
sgtitle('Ανάλυση Fourier του Σήματος x(t)','FontSize',14); 